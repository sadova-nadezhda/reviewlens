export function sentimentWeights(shares: SentimentShares): Weighted<Sentiment> {
  return SENTIMENTS.map((sentiment) => [sentiment, shares[sentiment]] as const)
}

/** Итоговые доли тональностей: сумма долей по темам, взвешенная по весам тем. */
export function overallSentimentShares(topics: Record<Topic, TopicSpec> = TOPICS): SentimentShares {
  const totalWeight = TOPIC_KEYS.reduce((sum, topic) => sum + topics[topic].weight, 0)
  const share = (sentiment: Sentiment) =>
    TOPIC_KEYS.reduce((sum, topic) => sum + topics[topic].weight * topics[topic].shares[sentiment], 0) /
    totalWeight

  return { positive: share('positive'), neutral: share('neutral'), negative: share('negative') }
}
